"""hs-eval: run evaluations and write versioned result files under eval/results/, plus a generated
Markdown table (eval/results/latest.md) that the README links to. Numbers are never typed by hand."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from hindsight.api.service import RESULTS_DIR, latest_impact_by_repo, primary_web
from hindsight.core.config import ROOT, load_settings
from hindsight.core.db import connect, get_meta
from hindsight.eval.impact_replay import run
from hindsight.eval.rca import campaign

LABELS = {
    "hindsight": "Hindsight (co-change + service calls + same service + recency)",
    "cochange_only": "Baseline: co-change only",
    "same_directory": "Baseline: same directory, most recent first",
    "most_frequent": "Baseline: most frequently changed files",
}


def markdown(result: dict[str, Any]) -> str:
    repo = result.get("repo") or {}
    lines = [
        "# Latest evaluation results",
        "",
        "Generated by `make eval`; do not edit by hand.",
        "",
        f"- Repository: {repo.get('web', '?')} at `{str(repo.get('head_sha', ''))[:7]}`",
        f"- Held-out commits (newest 15%, 2 to 30 files): **n = {result['n_queries']}**",
        f"- Bot share of all commits (filtered out): {result['bot_share']:.1%}",
        f"- Result file: `{Path(result['result_file']).relative_to(ROOT)}` (created {result['created_at']})",
        "",
        "| Method | P@5 | R@10 | Hit@3 |",
        "|---|---|---|---|",
    ]
    for name, metrics in result["methods"].items():
        cells = [
            f"{m['value']:.3f} [{m['ci_low']:.3f}, {m['ci_high']:.3f}]" for m in metrics.values()
        ]
        lines.append(f"| {LABELS.get(name, name)} | " + " | ".join(cells) + " |")
    lines += [
        "",
        "Brackets are 95% bootstrap confidence intervals (1,000 resamples, seed 13). Weights are the",
        "DESIGN §2.2 defaults and were not tuned. Protocol: docs/EVALUATION.md §2.",
        "",
    ]
    return "\n".join(lines)


def _cells(metrics: dict[str, dict[str, float]]) -> list[str]:
    return [f"{m['value']:.3f} [{m['ci_low']:.3f}, {m['ci_high']:.3f}]" for m in metrics.values()]


def rca_markdown(result: dict[str, Any]) -> str:
    ttd = result["ttd_s"]
    lines = [
        "## Incident triage (fault campaign, synthetic)",
        "",
        f"- Runs: **n = {result['n_runs']}** ({result['detected']} detected), one injected fault each,"
        " after ≥ 5 min of healthy traffic. Faults and deploys are synthetic.",
        f"- Time to detect: median {ttd['median']} s, p90 {ttd['p90']} s",
        f"- False alerts during healthy traffic: {result['false_alerts_per_hour']} per hour",
        f"- Result file: `{Path(result['result_file']).relative_to(ROOT)}` (created {result['created_at']})",
        "",
        "| Culprit ranking | Top-1 | Top-3 |",
        "|---|---|---|",
    ]
    names = {
        "hindsight": "Hindsight (culprit vs victim)",
        "baseline_most_errors": "Baseline: most error lines",
        "baseline_largest_increase": "Baseline: largest error increase",
    }
    for name, metrics in result["culprit"].items():
        lines.append(f"| {names.get(name, name)} | " + " | ".join(_cells(metrics)) + " |")
    lines += ["", "| Incident → change | Hit@1 | Hit@3 |", "|---|---|---|"]
    for name, metrics in result["correlation"].items():
        label = "Hindsight (candidates)" if name == "hindsight" else "Baseline: most recent deploy"
        lines.append(f"| {label} | " + " | ".join(_cells(metrics)) + " |")
    lines.append("")
    return "\n".join(lines)


def retrieval_markdown(result: dict[str, Any]) -> str:
    repo = result.get("repo") or {}
    lines = [
        "## Finding the evidence (retrieval, automatic proxy)",
        "",
        f"- Task: from a pull request's or commit's title alone (\"#N\" removed), find the issue it links to in"
        f" {repo.get('owner', '?')}/{repo.get('name', '?')}. Only text recorded before that PR or commit is"
        ' searched. `fixes` uses explicit "Fixes #N" links; `references` uses plain "#N" mentions (weaker key).',
        f"- Semantic search: local embeddings (`{result['embed_model']}`); hybrid = rank fusion of keyword and semantic,"
        " as the answers use it.",
        f"- Result file: `{Path(result['result_file']).relative_to(ROOT)}` (created {result['created_at']})",
        "",
        "| Answer key | n | Method | Hit@1 | Hit@5 | Hit@10 | MRR |",
        "|---|---|---|---|---|---|---|",
    ]
    names = {
        "keyword": "Keyword (BM25)",
        "semantic": "Semantic only",
        "hybrid": "Hybrid (used by answers)",
    }
    for key, block in result["sets"].items():
        first = True
        for name, metrics in block["methods"].items():
            label = f"{key} | {block['n_queries']}" if first else " | "
            lines.append(
                f"| {label} | {names.get(name, name)} | " + " | ".join(_cells(metrics)) + " |"
            )
            first = False
    lines.append("")
    return "\n".join(lines)


def ask_markdown(result: dict[str, Any]) -> str:
    repo = result.get("repo") or {}
    sets = result["sets"]
    ans = sets["answerable"]

    def cell(m: dict[str, float]) -> str:
        return f"{m['value']:.3f} [{m['ci_low']:.3f}, {m['ci_high']:.3f}]"

    lines = [
        "## Why-answers (answer key: generated links + hand-written trick questions)",
        "",
        f"- Repository: {repo.get('web', '?')} at `{str(repo.get('head_sha', ''))[:7]}`;"
        f" code `{str(result.get('code_sha', ''))[:7]}`; model: {result['model']}",
        f'- Answerable (generated from explicit "Fixes #N" links, gold = the issue): **n = {ans["n"]}**,'
        " each asked twice: naming the commit hash, and naming only the file and the change",
        f"- Result file: `{Path(result['result_file']).relative_to(ROOT)}` (created {result['created_at']})",
        "",
        "| Question names | Measure | Hindsight | Keyword search only |",
        "|---|---|---|---|",
    ]
    for key, label in (("answerable", "commit hash"), ("answerable_no_hash", "file + change")):
        block = sets.get(key)
        if not block:
            continue
        ours, kw = block["methods"]["hindsight"], block["methods"]["keyword_only"]
        lines += [
            f"| {label} | Answered | {cell(ours['answered'])} | - |",
            f"| {label} | Linked issue among the sources | {cell(ours['gold_in_sources'])}"
            f" | {cell(kw['gold_in_sources'])} |",
            f"| {label} | Linked issue cited by a claim | {cell(ours['gold_cited'])} | - |",
        ]
    lines.append("")
    trick = sets.get("trick")
    if trick:
        plain = trick["methods"].get("model_without_sources")
        lines += [
            f'- Trick questions (hand-written, committed before they were first scored; right answer is "not found"): **n = {trick["n"]}**',
            "",
            "| Measure | Hindsight | Same model, no sources |",
            "|---|---|---|",
            f'| Answered "not found" | {cell(trick["methods"]["hindsight"]["not_found"])}'
            f" | {cell(plain['not_found']) + f' (n={trick["n_plain_model_replies"]})' if plain else 'not run (no model)'} |",
            "",
        ]
    else:
        lines += ["- Trick questions: not measured yet (eval/questions-trick.yaml is missing).", ""]
    lines += [
        "Brackets are 95% bootstrap confidence intervals (1,000 resamples, seed 13). Protocol:"
        " docs/EVALUATION.md §3. A person checks 10 answers separately (the ask-handcheck CSV).",
        "",
    ]
    return "\n".join(lines)


def heal_markdown(result: dict[str, Any]) -> str:
    cfg = result["config"]
    n = cfg["n_mutations"]
    lines = [
        "## Test healing (mutation harness, synthetic)",
        "",
        f"- {n['cosmetic']} cosmetic and {n['defect']} defect mutations of the demo shop's pages, applied in"
        " the test browser only; tests: " + ", ".join(f"`{t}`" for t in cfg["tests"]),
        f"- Accept a heal only if similarity ≥ θ {cfg['theta']} and ≥ δ {cfg['delta']} above the next"
        f" candidate; {cfg['reruns_before_heal']} re-runs first to rule out flakiness",
        f"- Result file: `{Path(result['result_file']).relative_to(ROOT)}` (created {result['created_at']})",
    ]
    if result.get("invalid_tests"):
        lines.append(
            f"- Tests that did not pass 3/3 on the clean shop (left out): {sorted(result['invalid_tests'])}"
        )
    if result.get("not_applied"):
        lines.append(
            f"- Mutation/test pairs where the rewrite did not apply (left out): {len(result['not_applied'])}"
        )
    lines += [
        "",
        "| Method | Heal rate (broken locators) | Cosmetic kept green | Correct refusals (defects) | False heals | Median heal time |",
        "|---|---|---|---|---|---|",
    ]
    names = {
        "similo": "Hindsight healer (Similo-style)",
        "naive": "Baseline: same tag and text",
        "none": "Baseline: no healing",
    }
    for name, m in result["methods"].items():
        cells = [
            f"{m[k]['value']:.3f} [{m[k]['ci_low']:.3f}, {m[k]['ci_high']:.3f}]"
            for k in ("heal_rate", "cosmetic_kept_green", "correct_refusals")
        ]
        ms = m["heal_latency_ms_median"]
        lines.append(
            f"| {names.get(name, name)} | {cells[0]} (n={m['n_broken']}) | {cells[1]} (n={m['n_cosmetic']})"
            f" | {cells[2]} (n={m['n_defect']}) | **{m['false_heals']}** | {f'{ms / 1000:.1f} s' if ms else '-'} |"
        )
    lines += ["", "Heal time includes the re-runs that rule out flakiness.", ""]
    return "\n".join(lines)


def others_markdown(results: list[dict[str, Any]]) -> str:
    lines = [
        "## Other public repositories (same protocol, same default weights)",
        "",
        "Checks that the impact check is not fitted to the main repository. Each repository has its"
        " own data folder; reproduce with `make try-repo REPO=<url>`.",
        "",
        "| Repository | n | Method | P@5 | R@10 | Hit@3 |",
        "|---|---|---|---|---|---|",
    ]
    for result in results:
        repo = result.get("repo") or {}
        name = f"{repo.get('owner', '?')}/{repo.get('name', '?')} `{str(repo.get('head_sha', ''))[:7]}`"
        for method, metrics in result["methods"].items():
            lines.append(
                f"| {name} | {result['n_queries']} | {LABELS.get(method, method)} | "
                + " | ".join(_cells(metrics))
                + " |"
            )
            name = ""
    lines += ["", "Result files: " + ", ".join(f"`{r['result_file']}`" for r in results), ""]
    return "\n".join(lines)


def write_latest(primary: str | None = None) -> str:
    parts = []
    impact = latest_impact_by_repo(RESULTS_DIR)
    if primary is None:
        primary = primary_web(load_settings())
    others = []
    for web, path in sorted(impact.items()):
        data = json.loads(path.read_text())
        data["result_file"] = str(path)
        if web == primary:
            parts.insert(0, markdown(data))
        else:
            data["result_file"] = str(path.relative_to(ROOT))
            others.append(data)
    if others:
        parts.append(others_markdown(others))
    asked = sorted(RESULTS_DIR.glob("ask-*.json"))
    if asked:
        data = json.loads(asked[-1].read_text())
        data["result_file"] = str(asked[-1])
        parts.append(ask_markdown(data))
    retrieval = sorted(RESULTS_DIR.glob("retrieval-*.json"))
    if retrieval:
        data = json.loads(retrieval[-1].read_text())
        data["result_file"] = str(retrieval[-1])
        parts.append(retrieval_markdown(data))
    heal = sorted(RESULTS_DIR.glob("heal-*.json"))
    if heal:
        data = json.loads(heal[-1].read_text())
        data["result_file"] = str(heal[-1])
        parts.append(heal_markdown(data))
    rca = sorted(RESULTS_DIR.glob("rca-*.json"))
    if rca:
        data = json.loads(rca[-1].read_text())
        data["result_file"] = str(rca[-1])
        parts.append(rca_markdown(data))
    text = "\n".join(parts)
    (RESULTS_DIR / "latest.md").write_text(text)
    return text


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="hs-eval", description=__doc__)
    parser.add_argument(
        "what",
        choices=["impact", "rca", "heal", "retrieval", "ask-questions", "ask", "all", "report"],
        help="impact: history replay (fast); ask-questions: write eval/questions.yaml from explicit"
        " links; ask: score the why-answers; rca: fault campaign on the local cluster (slow);"
        " report: only rewrite eval/results/latest.md from the result files",
    )
    parser.add_argument("--runs", type=int, default=10, help="rca: number of injected faults")
    parser.add_argument(
        "--healthy", type=int, default=300, help="rca: seconds of healthy traffic per run"
    )
    args = parser.parse_args(argv)
    settings = load_settings()
    if args.what in ("impact", "all"):
        conn = connect(settings.db_path)
        try:
            web = (get_meta(conn, "repo") or {}).get("web", "")
            primary = primary_web(settings)
            command = "make eval" if web in ("", primary) else f"make try-repo REPO={web}"
            run(conn, RESULTS_DIR, command=command)
        finally:
            conn.close()
    if args.what == "ask-questions":
        from hindsight.eval.ask_eval import QUESTIONS, write_questions

        conn = connect(settings.db_path)
        try:
            qs = write_questions(conn)
        finally:
            conn.close()
        print(f"{len(qs)} answerable questions written to {QUESTIONS.relative_to(ROOT)}")
        return 0
    if args.what == "ask":
        from hindsight.api.service import repo_dir
        from hindsight.core.llm import Chain
        from hindsight.eval.ask_eval import QUESTIONS, TRICK, load, score

        answerable = load(QUESTIONS)
        if not answerable:
            print("no questions yet: run `hs-eval ask-questions` first")
            return 1
        conn = connect(settings.db_path)
        try:
            result = score(
                conn,
                answerable,
                load(TRICK),
                repo=repo_dir(conn),
                chain=Chain.from_settings(conn, settings),
                out_dir=RESULTS_DIR,
            )
        finally:
            conn.close()
        if "trick" not in result["sets"]:
            print(f"trick questions not measured: write {TRICK.relative_to(ROOT)} first")
    if args.what == "rca":
        campaign(settings, runs=args.runs, healthy_s=args.healthy, out_dir=RESULTS_DIR)
    if args.what == "retrieval":
        from hindsight.core.embed import OllamaEmbedder, has_index
        from hindsight.eval.retrieval import run as run_retrieval

        embedder = OllamaEmbedder(settings.ollama_host, settings.embed_model)
        conn = connect(settings.db_path)
        try:
            if not has_index(conn, settings.embed_model):
                print("no semantic index yet: run `make embed` first")
                return 1
            run_retrieval(conn, embedder, RESULTS_DIR)
        finally:
            conn.close()
    if args.what == "heal":
        from hindsight.eval.heal import evaluate
        from hindsight.sentinel.service import generate_all
        from hindsight.sentinel.store import get_spec

        conn = connect(settings.db_path)
        try:
            with conn:
                generated = generate_all(conn)
            specs = [s for g in generated if (s := get_spec(conn, g["id"])) is not None]
        finally:
            conn.close()
        evaluate(specs, settings.target_url, RESULTS_DIR)
    print(write_latest())
    return 0


if __name__ == "__main__":
    sys.exit(main())
