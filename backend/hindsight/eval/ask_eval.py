"""Ask evaluation (docs/EVALUATION.md §3, mixed answer key).

Answerable questions are generated by code from explicit links, so nobody on the team picks them:
a commit (or the PR it belongs to) that says "Fixes #N", where the text of issue N was read. The
question names a file the commit changed, the commit and its subject ("#N" removed); the gold
source is issue N, the reason the change was made. Trick questions are written by hand, before
any run, in eval/questions-trick.yaml; the right answer to every one of them is "not found".

Scored per question, with 95% bootstrap intervals (1,000 resamples, seed 13):
- answerable: answered, the linked issue among the sources, the linked issue cited by a claim;
- trick: answered "not found";
baselines: keyword search alone (the linked issue among its top results), and, when a model is
configured, the same model asked without any sources (does it "answer" trick questions?).

Ask is scored on the full graph: it explains changes that already happened (not a prediction)."""

from __future__ import annotations

import csv
import json
import re
import sqlite3
import subprocess
import time
from collections.abc import Callable
from pathlib import Path
from typing import Any

import yaml

from hindsight.brain.ask import PACK_SIZE, ask
from hindsight.core.config import ROOT
from hindsight.core.db import get_meta
from hindsight.core.llm import Chain
from hindsight.core.schemas import Answer
from hindsight.core.text import content_terms, fts_term
from hindsight.eval.rca import _ci as bootstrap_ci

QUESTIONS = ROOT / "eval" / "questions.yaml"
TRICK = ROOT / "eval" / "questions-trick.yaml"
COMMAND = "make eval-ask"
LIMIT = 100
SOURCE_EXT = (".go", ".py", ".cs", ".js", ".ts", ".java", ".rb", ".rs", ".kt", ".cpp", ".c")
_ISSUE_REF = re.compile(
    r"\b(?:fix(?:es|ed)?|close[sd]?|resolve[sd]?)\b\s*:?\s*#\d+|\(?#\d+\)?", re.IGNORECASE
)

AskFn = Callable[..., Answer]


def clean_subject(subject: str) -> str:
    """The commit subject without issue numbers or closing keywords (they would give the answer)."""
    text = _ISSUE_REF.sub(" ", subject)
    return re.sub(r"\s+", " ", text).strip(" .,:;-")


def _pick_file(paths: list[str]) -> str | None:
    def rank(path: str) -> tuple[int, int, str]:
        low = path.lower()
        test = int("test" in low)
        source = int(not low.endswith(SOURCE_EXT))
        return (test, source, path)

    return min(paths, key=rank) if paths else None


def generate(conn: sqlite3.Connection, limit: int = LIMIT) -> list[dict[str, Any]]:
    """One question per fixing commit, oldest first. Deterministic for a given graph."""
    rows = conn.execute(
        "SELECT s.id AS src, s.kind AS skind, s.key AS skey, d.key AS issue FROM edges e"
        " JOIN nodes s ON s.id = e.src JOIN nodes d ON d.id = e.dst"
        " WHERE e.kind = 'FIXES' AND e.provenance = 'explicit' AND d.kind = 'Issue'"
        " AND s.kind IN ('Commit', 'PR')"
        " AND EXISTS (SELECT 1 FROM spans sp WHERE sp.node_id = d.id)"
        " ORDER BY s.ts, s.id, d.key"
    ).fetchall()
    by_commit: dict[int, dict[str, Any]] = {}
    for r in rows:
        if r["skind"] == "Commit":
            commits = [r["src"]]
        else:  # the PR's commits (title suffix or merge SHA)
            commits = [
                c[0]
                for c in conn.execute(
                    "SELECT e.src FROM edges e JOIN nodes c ON c.id = e.src"
                    " WHERE e.dst = ? AND e.kind = 'PART_OF' AND c.kind = 'Commit' ORDER BY c.ts",
                    (r["src"],),
                )
            ]
        for cid in commits[:1]:
            entry = by_commit.setdefault(cid, {"gold": [], "pr": None})
            if r["issue"] not in entry["gold"]:
                entry["gold"].append(r["issue"])
            if r["skind"] == "PR":
                entry["pr"] = r["skey"]
    out: list[dict[str, Any]] = []
    for cid, entry in by_commit.items():
        c = conn.execute(
            "SELECT n.key, n.title, n.ts, m.ok FROM nodes n JOIN commits m ON m.id = n.id"
            " WHERE n.id = ?",
            (cid,),
        ).fetchone()
        if c is None or not c["ok"]:
            continue  # bot, sweep or merge commit
        files = [
            f[0].removeprefix("file:")
            for f in conn.execute(
                "SELECT n.key FROM edges e JOIN nodes n ON n.id = e.dst"
                " WHERE e.src = ? AND e.kind = 'MODIFIES' AND n.kind = 'File'",
                (cid,),
            )
        ]
        path = _pick_file(files)
        subject = clean_subject((c["title"] or "").splitlines()[0] if c["title"] else "")
        if path is None or len(content_terms(subject)) < 2:
            continue
        sha = c["key"].removeprefix("commit:")
        out.append(
            {
                "id": f"q{len(out) + 1:03d}",
                "question": f'Why was {path} changed in commit {sha[:7]} ("{subject}")?',
                "file": path,
                "commit": sha,
                "gold": entry["gold"],
                "pr": entry["pr"],
            }
        )
        if len(out) >= limit:
            break
    return out


def write_questions(conn: sqlite3.Connection, path: Path = QUESTIONS) -> list[dict[str, Any]]:
    qs = generate(conn)
    repo = get_meta(conn, "repo", {}) or {}
    header = (
        "# Generated by `hs-eval ask-questions`; do not edit by hand.\n"
        f"# Repository: {repo.get('web', '?')} at {str(repo.get('head_sha', ''))[:7]};"
        f" created {time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime())}\n"
        "# Each question: a file a fixing commit changed, the commit and its subject (issue numbers\n"
        '# removed). Gold: the issue the commit or its PR closes ("Fixes #N"). Protocol:\n'
        "# docs/EVALUATION.md §3.\n"
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(header + yaml.safe_dump({"questions": qs}, sort_keys=False, width=100))
    return qs


def load(path: Path) -> list[dict[str, Any]]:
    if not path.exists():
        return []
    data = yaml.safe_load(path.read_text()) or {}
    return [q for q in data.get("questions") or [] if q.get("question")]


def _keyword_nodes(conn: sqlite3.Connection, question: str, k: int) -> list[str]:
    """Baseline: keyword search alone (FTS5 BM25 over every recorded text), no graph."""
    terms = content_terms(question)
    if not terms:
        return []
    match = " OR ".join(fts_term(t) for t in terms)
    rows = conn.execute(
        "SELECT n.key FROM spans_fts f JOIN spans s ON s.id = f.rowid JOIN nodes n ON n.id = s.node_id"
        " WHERE spans_fts MATCH ? ORDER BY bm25(spans_fts) LIMIT ?",
        (match, k * 4),
    ).fetchall()
    return list(dict.fromkeys(r[0] for r in rows))[:k]


def _plain_model(chain: Chain, repo_name: str, question: str) -> bool | None:
    """Baseline: the same model, no sources. True when it gives an answer, None when no reply."""
    prompt = (
        f"You are asked about the open-source project {repo_name}. Answer from what you know. "
        'If you do not know, reply {"answer": null}. Reply only JSON: {"answer": "<one or two '
        f'sentences>"}}.\n\nQuestion: {question}'
    )
    reply = chain.complete_json(prompt)
    if reply is None:
        return None
    answer = reply.get("answer")
    return bool(isinstance(answer, str) and answer.strip())


def _code_sha() -> str:
    try:
        out = subprocess.run(
            ["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True, text=True, check=True
        )
        dirty = subprocess.run(
            ["git", "status", "--porcelain", "--untracked-files=no", "backend"],
            cwd=ROOT,
            capture_output=True,
            text=True,
            check=True,
        ).stdout.strip()
        # uncommitted code changes: the hash alone would not reproduce this run
        return out.stdout.strip() + ("-dirty" if dirty else "")
    except (OSError, subprocess.CalledProcessError):
        return ""


def _rate(values: list[bool]) -> dict[str, float]:
    return bootstrap_ci([1.0 if v else 0.0 for v in values])


_HASH_PHRASE = re.compile(r" in commit [0-9a-f]{7,40}\b")


def without_hash(question: str) -> str:
    """'Why was f changed in commit abc1234 ("s")?' → 'Why was f changed ("s")?'"""
    return _HASH_PHRASE.sub("", question)


def _model_line(model: Chain | None, rows: list[dict[str, Any]]) -> str:
    """Which model really answered: a configured model that never replied is not credited."""
    answered = [r for r in rows if r["status"] == "answered"]
    phrased = sum(1 for r in answered if r["mode"] == "llm")
    if model is None:
        return "none configured (quoted answers)"
    names = ", ".join(f"{p.name}/{p.model}" for p in model.providers)
    if not phrased:
        return f"none answered ({names} configured but did not reply; quoted answers)"
    return f"{names}: phrased {phrased} of {len(answered)} answers (the rest quoted)"


def score(
    conn: sqlite3.Connection,
    answerable: list[dict[str, Any]],
    trick: list[dict[str, Any]],
    *,
    repo: Path | None,
    chain: Chain | None,
    ask_fn: AskFn = ask,
    out_dir: Path | None = None,
) -> dict[str, Any]:
    repo_meta = get_meta(conn, "repo", {}) or {}
    repo_name = f"{repo_meta.get('owner', '?')}/{repo_meta.get('name', '?')}"
    model = chain if chain is not None and chain.configured else None
    rows: list[dict[str, Any]] = []
    for q in answerable:
        # with the hash, the commit's own links lead to the issue; without it (file and subject
        # only), search has to find the commit first: the harder, more telling variant
        for variant, question in (
            ("with_hash", q["question"]),
            ("no_hash", without_hash(q["question"])),
        ):
            ans = ask_fn(conn, question, repo=repo, file=q.get("file"), chain=model)
            gold = set(q.get("gold") or [])
            by_id = {e.id: e.node_key for e in ans.evidence}
            cited = {by_id.get(c, "") for claim in ans.claims for c in claim.cites}
            rows.append(
                {
                    "id": q["id"],
                    "set": "answerable" if variant == "with_hash" else "answerable_no_hash",
                    "question": question,
                    "gold": sorted(gold),
                    "status": ans.status,
                    "mode": ans.mode,
                    "gold_in_sources": bool(gold & set(by_id.values())),
                    "gold_cited": bool(gold & cited),
                    "keyword_gold_in_top": bool(
                        gold & set(_keyword_nodes(conn, question, PACK_SIZE))
                    ),
                    "claims": len(ans.claims),
                    "answer": " | ".join(c.text for c in ans.claims[:2]),
                    "cited": sorted(
                        {
                            e.url
                            for e in ans.evidence
                            if any(e.id in c.cites for c in ans.claims[:2])
                        }
                    ),
                    "notes": ans.notes,
                }
            )
    for q in trick:
        ans = ask_fn(conn, q["question"], repo=repo, file=q.get("file"), chain=model)
        rows.append(
            {
                "id": q.get("id", ""),
                "set": "trick",
                "question": q["question"],
                "status": ans.status,
                "mode": ans.mode,
                "plain_model_answered": _plain_model(model, repo_name, q["question"])
                if model
                else None,
                "claims": len(ans.claims),
                "notes": ans.notes,
            }
        )
    trick_rows = [r for r in rows if r["set"] == "trick"]
    sets: dict[str, Any] = {}
    for name in ("answerable", "answerable_no_hash"):
        ans_rows = [r for r in rows if r["set"] == name]
        sets[name] = {
            "n": len(ans_rows),
            "methods": {
                "hindsight": {
                    "answered": _rate([r["status"] == "answered" for r in ans_rows]),
                    "gold_in_sources": _rate([r["gold_in_sources"] for r in ans_rows]),
                    "gold_cited": _rate([r["gold_cited"] for r in ans_rows]),
                },
                "keyword_only": {
                    "gold_in_sources": _rate([r["keyword_gold_in_top"] for r in ans_rows]),
                },
            },
        }
    if trick_rows:
        methods: dict[str, Any] = {
            "hindsight": {"not_found": _rate([r["status"] == "not_found" for r in trick_rows])}
        }
        replied = [
            r["plain_model_answered"] for r in trick_rows if r["plain_model_answered"] is not None
        ]
        if replied:
            methods["model_without_sources"] = {"not_found": _rate([not a for a in replied])}
        sets["trick"] = {
            "n": len(trick_rows),
            "n_plain_model_replies": len(replied),
            "methods": methods,
        }
    result: dict[str, Any] = {
        "name": "ask_answer_key",
        "created_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "command": COMMAND,
        "code_sha": _code_sha(),
        "repo": repo_meta,
        "model": _model_line(model, rows),
        "questions_file": str(QUESTIONS.relative_to(ROOT)),
        "trick_file": str(TRICK.relative_to(ROOT)) if trick else None,
        "sets": sets,
        "rows": rows,
    }
    if out_dir is not None:
        out_dir.mkdir(parents=True, exist_ok=True)
        stamp = time.strftime("%Y%m%dT%H%M%SZ", time.gmtime())
        path = out_dir / f"ask-{stamp}.json"
        path.write_text(json.dumps(result, indent=2))
        result["result_file"] = str(path)
        hand_check(rows, out_dir / f"ask-handcheck-{stamp}.csv")
    return result


def hand_check(rows: list[dict[str, Any]], path: Path, k: int = 10) -> int:
    """Every n-th answered question, for a person to mark supported or not (reported separately,
    never folded into the automatic numbers). Returns how many rows were written."""
    answered = [r for r in rows if r["set"] == "answerable" and r["status"] == "answered"]
    step = max(1, len(answered) // k)
    picked = answered[::step][:k]
    with path.open("w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["id", "question", "answer", "cited", "supported (yes/no)", "checked by"])
        for r in picked:
            w.writerow([r["id"], r["question"], r["answer"], " ".join(r["cited"]), "", ""])
    return len(picked)
